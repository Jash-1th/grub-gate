// Helper functions for filtering restaurants
export const getPopularRestaurants = () => {
  return restaurantData
    .filter(restaurant => restaurant.isPopular)
    .sort((a, b) => b.rating - a.rating); // Sort by rating descending
};

export const getTopRatedRestaurants = () => {
  return restaurantData
    .filter(restaurant => restaurant.isTopRated)
    .sort((a, b) => b.rating - a.rating); // Sort by rating descending
};

export const getRestaurantsByPostalCode = (postalCode) => {
  if (!postalCode || postalCode.length < 3) return [];
  const prefix = postalCode.substring(0, 3).toUpperCase();
  return restaurantData
    .filter(restaurant => restaurant.postalCodes.includes(prefix))
    .sort((a, b) => b.rating - a.rating); // Sort by rating descending
};

export const filterRestaurantsByPreferences = (restaurants, preferences) => {
  if (!preferences || preferences.length === 0) return restaurants;
  
  return restaurants
    .filter(restaurant => 
      preferences.some(preference => 
        restaurant.preferences.includes(preference)
      )
    )
    .sort((a, b) => b.rating - a.rating); // Sort by rating descending
};

export const getFilteredRestaurants = (postalCode, preferences) => {
  let filteredRestaurants;
  
  if (postalCode && postalCode.length >= 3) {
    filteredRestaurants = getRestaurantsByPostalCode(postalCode);
  } else {
    filteredRestaurants = getPopularRestaurants();
  }
  
  if (preferences && preferences.length > 0) {
    filteredRestaurants = filterRestaurantsByPreferences(filteredRestaurants, preferences);
  }
  
  // Final sort by rating to ensure consistent ordering
  return filteredRestaurants.sort((a, b) => b.rating - a.rating);
};
